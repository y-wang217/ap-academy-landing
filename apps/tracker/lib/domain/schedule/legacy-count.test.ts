import { describe, expect, it } from "vitest";
import { parseSlot, textMonthSessions } from "./legacy-count";

// REQ-40 AC8: how the text-based monthly run counts a month.
describe("textMonthSessions", () => {
  it("one session per slot per matching weekday in the month", () => {
    // November 2026 has four Tuesdays and five Mondays.
    const s = textMonthSessions("Tue 17:00-18:00 | MPM2D Math | Jane Doe\nMon 18:00-19:30 | MHF4U | Bob Roe", "2026-11");
    expect(s.filter((x) => x.course === "MPM2D Math").map((x) => x.date)).toEqual(["2026-11-03", "2026-11-10", "2026-11-17", "2026-11-24"]);
    expect(s.filter((x) => x.course === "MHF4U").map((x) => [x.date, x.hours])).toEqual([
      ["2026-11-02", 1.5], ["2026-11-09", 1.5], ["2026-11-16", 1.5], ["2026-11-23", 1.5], ["2026-11-30", 1.5],
    ]);
  });

  it("ignores from and until, as the monthly run does", () => {
    const s = textMonthSessions("Wed 15:00-16:00 | SCH4U Chemistry | Jane Doe | from 2026-11-18\nFri 15:00-16:00 | SPH4U Physics | Jane Doe | until 2026-11-13", "2026-11");
    expect(s.map((x) => x.date)).toEqual(["2026-11-04", "2026-11-06", "2026-11-11", "2026-11-13", "2026-11-18", "2026-11-20", "2026-11-25", "2026-11-27"]);
  });

  it("the hours-only form counts too, and a missing course is Tutoring", () => {
    expect(textMonthSessions("Sat 2h", "2026-11").map((x) => [x.date, x.hours, x.course])).toEqual([
      ["2026-11-07", 2, "Tutoring"], ["2026-11-14", 2, "Tutoring"], ["2026-11-21", 2, "Tutoring"], ["2026-11-28", 2, "Tutoring"],
    ]);
  });

  it("an empty text counts nothing", () => {
    expect(textMonthSessions("", "2026-11")).toEqual([]);
  });

  it("a line the monthly run cannot read throws, as the run would stop", () => {
    expect(() => textMonthSessions("Generated by the scheduler\nTue 17:00-18:00 | A | B", "2026-11")).toThrow();
    expect(() => parseSlot("Tuesday at five")).toThrow(/Cannot parse schedule line/);
  });
});
