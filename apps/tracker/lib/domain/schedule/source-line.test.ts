import { describe, expect, it } from "vitest";
import { scheduleSourceLine } from "./source-line";

const SITE = "https://www.apacademy.ca";
const T1 = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
const T2 = "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb";

describe("scheduleSourceLine (REQ-34 AC1)", () => {
  it("is the fixed line with the teacher's week when one teacher has the open classes", () => {
    expect(scheduleSourceLine({ adoptedOn: "2026-10-21", staffIds: [T1], siteUrl: SITE })).toBe(
      `Generated by the scheduler since 2026-10-21. Edits to Weekly Schedule are replaced. Change classes at ${SITE}/tracker/schedule?staffId=${T1}`,
    );
  });

  it("dedupes teacher ids", () => {
    expect(scheduleSourceLine({ adoptedOn: "2026-10-21", staffIds: [T1, T1], siteUrl: SITE })).toMatch(/\?staffId=aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa$/);
  });

  it("links to every teacher's week when there are several teachers, or none", () => {
    expect(scheduleSourceLine({ adoptedOn: "2026-10-21", staffIds: [T1, T2], siteUrl: SITE })).toMatch(/ at https:\/\/www\.apacademy\.ca\/tracker\/schedule\?view=all$/);
    expect(scheduleSourceLine({ adoptedOn: "2026-10-21", staffIds: [], siteUrl: SITE })).toMatch(/\/tracker\/schedule\?view=all$/);
  });

  it("has no newline, no em dash and fits one Notion text segment", () => {
    const line = scheduleSourceLine({ adoptedOn: "2026-10-21", staffIds: [T1], siteUrl: SITE });
    expect(line).not.toMatch(/\n/);
    expect(line).not.toContain("—");
    expect(line.length).toBeLessThanOrEqual(2000);
  });
});
