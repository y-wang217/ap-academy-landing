/**
 * The one line the scheduler writes to a student's Schedule Source property
 * once they are adopted (REQ-34, tracker ADR 0067). It says the schedule is
 * generated, since when, and where to change classes. Pure: no React, Next or
 * Supabase. Weekly Schedule keeps slot lines only, so billing never sees it.
 */
export function scheduleSourceLine(input: { adoptedOn: string; staffIds: string[]; siteUrl: string }): string {
  const staff = [...new Set(input.staffIds)];
  const query = staff.length === 1 ? `staffId=${staff[0]}` : "view=all";
  return `Generated by the scheduler since ${input.adoptedOn}. Edits to Weekly Schedule are replaced. Change classes at ${input.siteUrl}/tracker/schedule?${query}`;
}
